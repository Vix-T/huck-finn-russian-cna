"""Word-adjacency networks: data/interim/tagged/Ru#.tsv -> data/interim/networks/.

One directed network per text. Nodes are the lemmas of word tokens (is_word = 1; Roman numerals are not words), lowercased
and mapped by [networks].lemma_char_map. Within each sentence there is an edge from every word
to the next word; tokens that are not words (punctuation, numbers, abbreviations) are skipped,
so words separated by a comma are still linked. No edge crosses a sentence boundary. Self-loops
(a lemma followed by itself) are dropped and counted. Edge counts are kept for weighted measures;
the motif graph is unweighted.

The 13 connected 3-node triads are counted exactly with igraph (motifs_randesu) and with
networkx (triadic_census); the run fails unless the two agree. Triad classes are identified by
mfinder's subgraph ID, decoded here from mfinder's adjacency-matrix scheme (mfinder manual §3.3,
comment 7; motif_ids.c): ID = sum of a[i][j] * 2**(3i + j) over the 3x3 adjacency matrix, and
the class representative is the smallest ID over the six vertex orderings.

Outputs per text: Ru#_edges.tsv (source lemma, target lemma, count), Ru#_nodes.tsv (id, lemma),
Ru#_mfinder.txt (source id, target id, weight 1) and Ru#_triads.tsv; plus
docs/networks/network_report.md.

Usage:
    uv run python -m huckfinn_cna.networks [--config PATH]
    uv run python -m huckfinn_cna.networks --triad-table   # print the [[networks.triads]] block
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import Counter
from itertools import permutations
from pathlib import Path

import igraph as ig
import networkx as nx

from huckfinn_cna.config import DEFAULT_CONFIG, load_config, repo_path
from huckfinn_cna.tag import is_word, read_tagged


# A triad has three nodes; networkx's triadic census exists only for this size, so
# [networks].motif_size must equal it.
TRIAD_SIZE = 3


class NetworkError(Exception):
    pass


# --- Triad classes ----------------------------------------------------------------


def adjacency_id(edges: list[tuple[int, int]], order: tuple[int, ...]) -> int:
    """mfinder ID of a subgraph after relabelling vertex v as order[v]: sum of 2**(n*i + j) per edge i->j."""
    n = len(order)
    return sum(2 ** (n * order[i] + order[j]) for i, j in edges)


def mfinder_id(edges: list[tuple[int, int]], n: int) -> int:
    """Canonical mfinder ID: the smallest ID over all vertex orderings (motif_ids.c keeps the
    isomorphic IDs in an ascending list and takes the first)."""
    return min(adjacency_id(edges, order) for order in permutations(range(n)))


def decode_triad_classes(size: int) -> list[dict]:
    """The connected directed classes of `size` nodes: mfinder ID, networkx triad code, igraph class.

    Every igraph isoclass is drawn as a graph, and its mfinder ID and triad code are computed from
    its edges, so nothing in the table is typed by hand.
    """
    classes = []
    # motifs_randesu returns one entry per isoclass, so its length on any graph is the class count.
    n_classes = len(ig.Graph(n=size, directed=True).motifs_randesu(size=size))
    for cls in range(n_classes):
        g = ig.Graph.Isoclass(size, cls, directed=True)
        if not g.is_connected(mode="weak"):
            continue
        edges = g.get_edgelist()
        nxg = nx.DiGraph()
        nxg.add_nodes_from(range(size))
        nxg.add_edges_from(edges)
        classes.append({"mfinder_id": mfinder_id(edges, size), "triad_code": nx.triad_type(nxg),
                        "igraph_class": cls})
    return sorted(classes, key=lambda c: c["mfinder_id"])


def triad_table_toml(classes: list[dict]) -> str:
    lines = ["# Generated by `uv run python -m huckfinn_cna.networks --triad-table`. Do not edit by hand."]
    for c in classes:
        lines += ["[[networks.triads]]",
                  f"mfinder_id = {c['mfinder_id']}",
                  f"triad_code = \"{c['triad_code']}\"",
                  f"igraph_class = {c['igraph_class']}"]
    return "\n".join(lines) + "\n"


# --- Building the network ---------------------------------------------------------


def node_label(lemma: str, char_map: dict[str, str]) -> str:
    return "".join(char_map.get(ch, ch) for ch in lemma.lower())


def sentence_lemmas(rows: list[dict], char_map: dict[str, str]) -> list[list[str]]:
    """Node labels of the word tokens of each sentence, in text order.

    The is_word column must equal tag.is_word(token); a tagged file written under an older word rule
    fails the run (re-tag it).
    """
    sentences: dict[str, list[str]] = {}
    for r in rows:
        words = sentences.setdefault(r["sent_id"], [])
        word = is_word(r["token"])
        if (r["is_word"] == "1") != word:
            raise NetworkError(f"is_word column {r['is_word']} for {r['token']!r} in sentence {r['sent_id']} "
                               "disagrees with tag.is_word; re-tag (delete data/interim/tagged/Ru#.tsv)")
        if word:
            if not r["lemma"]:
                raise NetworkError(f"empty lemma for word token {r['token']!r} in sentence {r['sent_id']}")
            words.append(node_label(r["lemma"], char_map))
    return list(sentences.values())


def count_edges(sentences: list[list[str]]) -> tuple[Counter, Counter]:
    """Adjacent word pairs within sentences: (edge counts without self-loops, self-loop counts)."""
    edges, loops = Counter(), Counter()
    for words in sentences:
        for a, b in zip(words, words[1:]):
            (loops if a == b else edges)[a, b] += 1
    return edges, loops


def node_ids(sentences: list[list[str]]) -> dict[str, int]:
    """1-based ids for every node label, in sorted order (mfinder takes the highest id as the node count)."""
    return {lemma: i for i, lemma in enumerate(sorted({w for words in sentences for w in words}), start=1)}


def mutual_pairs(edges) -> int:
    """Unordered node pairs joined in both directions."""
    present = set(edges)
    return sum(1 for a, b in present if a < b and (b, a) in present)


def isolated_nodes(ids: dict[str, int], edges) -> int:
    linked = {x for pair in edges for x in pair}
    return sum(1 for lemma in ids if lemma not in linked)


# --- Triad counts -----------------------------------------------------------------


def count_triads_igraph(n_nodes: int, id_edges: list[tuple[int, int]], classes: list[dict]) -> dict[int, int]:
    """Exact counts of the connected triads (mfinder ID -> count); id_edges use 1-based ids."""
    g = ig.Graph(n=n_nodes, edges=[(s - 1, t - 1) for s, t in id_edges], directed=True)
    counts = g.motifs_randesu(size=TRIAD_SIZE)
    out = {}
    for c in classes:
        value = counts[c["igraph_class"]]
        if isinstance(value, float) and (math.isnan(value) or value != int(value)):
            raise NetworkError(f"igraph gave a non-integer count {value} for class {c['igraph_class']}")
        out[c["mfinder_id"]] = int(value)
    return out


def count_triads_networkx(n_nodes: int, id_edges: list[tuple[int, int]], classes: list[dict]) -> dict[int, int]:
    g = nx.DiGraph()
    g.add_nodes_from(range(1, n_nodes + 1))
    g.add_edges_from(id_edges)
    census = nx.triadic_census(g)
    return {c["mfinder_id"]: census[c["triad_code"]] for c in classes}


def checked_triads(n_nodes: int, id_edges: list[tuple[int, int]], classes: list[dict]) -> dict[int, int]:
    a = count_triads_igraph(n_nodes, id_edges, classes)
    b = count_triads_networkx(n_nodes, id_edges, classes)
    if a != b:
        diff = {k: (a[k], b[k]) for k in a if a[k] != b[k]}
        raise NetworkError(f"igraph and networkx triad counts differ (id: igraph, networkx): {diff}")
    return a


# --- mfinder cross-check ----------------------------------------------------------


def read_mfinder_input(path: Path) -> tuple[int, list[tuple[int, int]]]:
    """(node count, edges) of an mfinder input file; mfinder takes the highest id as the node count."""
    edges = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            s, t, _ = line.split()
            edges.append((int(s), int(t)))
    return max(max(e) for e in edges), edges


def read_mfinder_nreal(path: Path) -> dict[int, int]:
    """NREAL per subgraph ID from the 'Full list of subgraphs' section of an mfinder _OUT.txt file."""
    lines = path.read_text(encoding="latin-1").splitlines()
    start = next((i for i, ln in enumerate(lines) if ln.startswith("Full list of subgraphs")), None)
    if start is None:
        raise NetworkError(f"no 'Full list of subgraphs' section in {path}")
    nreal = {}
    for ln in lines[start + 1:]:
        fields = ln.split()
        if len(fields) >= 2 and fields[0].isdigit():
            nreal.setdefault(int(fields[0]), int(fields[1]))
    return nreal


def compare_nreal(mfinder_input: Path, mfinder_out: Path, classes: list[dict]) -> dict[int, tuple[int, int]]:
    """mfinder ID -> (mfinder NREAL, exact count) for every class; raises unless all agree."""
    n_nodes, edges = read_mfinder_input(mfinder_input)
    exact = checked_triads(n_nodes, sorted(set(edges)), classes)
    nreal = read_mfinder_nreal(mfinder_out)
    if set(nreal) != set(exact):
        raise NetworkError(f"mfinder subgraph IDs {sorted(nreal)} differ from the decoded IDs {sorted(exact)}")
    pairs = {k: (nreal[k], exact[k]) for k in sorted(exact)}
    diff = {k: v for k, v in pairs.items() if v[0] != v[1]}
    if diff:
        raise NetworkError(f"mfinder NREAL differs from the exact counts (id: mfinder, exact): {diff}")
    return pairs


# --- Files ------------------------------------------------------------------------


def write_tsv(path: Path, header: list[str], rows) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, delimiter="\t", lineterminator="\n", quoting=csv.QUOTE_NONE, quotechar=None)
        writer.writerow(header)
        writer.writerows(rows)


def mfinder_lines(id_edges: list[tuple[int, int]], weight: int) -> list[str]:
    lines = [f"{s} {t} {weight}" for s, t in id_edges]
    if len(set(lines)) != len(lines):
        raise NetworkError("duplicate lines in the mfinder edge list")
    return lines


def build_text(rows: list[dict], cfg: dict, classes: list[dict]) -> dict:
    """Network, statistics and triad counts for one text's tagged rows."""
    net = cfg["networks"]
    sentences = sentence_lemmas(rows, net["lemma_char_map"])
    edges, loops = count_edges(sentences)
    ids = node_ids(sentences)
    id_edges = sorted((ids[a], ids[b]) for a, b in edges)
    return {
        "sentences": sentences, "edges": edges, "ids": ids, "id_edges": id_edges,
        "stats": {
            "sentences": len(sentences),
            "word_tokens": sum(len(w) for w in sentences),
            "skipped_non_word_tokens": sum(1 for r in rows if r["is_word"] == "0" and r["is_punct"] == "0"),
            "nodes": len(ids),
            "isolated_nodes": isolated_nodes(ids, edges),
            "edges": len(edges),
            "edge_weight_total": sum(edges.values()),
            "mutual_pairs": mutual_pairs(edges),
            "self_loops_dropped": sum(loops.values()),
            "self_loop_lemmas": len(loops),
            # Diagnostic only: distinct edges if the same lemmas were linked across sentence
            # boundaries, as in the old pipeline (whole text as one token stream).
            "edges_if_crossing": len(count_edges([[w for words in sentences for w in words]])[0]),
        },
        "triads": checked_triads(len(ids), id_edges, classes),
    }


def write_text(out_dir: Path, text_id: str, result: dict, cfg: dict, classes: list[dict]) -> None:
    ids, edges = result["ids"], result["edges"]
    label = {i: lemma for lemma, i in ids.items()}
    write_tsv(out_dir / f"{text_id}_nodes.tsv", ["id", "lemma"], sorted((i, lemma) for lemma, i in ids.items()))
    write_tsv(out_dir / f"{text_id}_edges.tsv", ["source", "target", "count"],
              [(label[s], label[t], edges[label[s], label[t]]) for s, t in result["id_edges"]])
    (out_dir / f"{text_id}_mfinder.txt").write_text(
        "\n".join(mfinder_lines(result["id_edges"], cfg["networks"]["mfinder_edge_weight"])) + "\n", encoding="utf-8")
    write_tsv(out_dir / f"{text_id}_triads.tsv", ["mfinder_id", "triad_code", "igraph_class", "count"],
              [(c["mfinder_id"], c["triad_code"], c["igraph_class"], result["triads"][c["mfinder_id"]]) for c in classes])


# --- Report -----------------------------------------------------------------------


def old_sizes(config: dict) -> dict[str, dict]:
    """Nodes and edges of the archived mfinder input networks, from the data audit."""
    audit = json.loads(repo_path(config, "audit_json").read_text(encoding="utf-8"))
    return {t: audit["mfinder"]["inputs"][f"{t}_mfinder_input.txt"] for t in config["corpus"]["texts"]}


def num(x: int) -> str:
    return f"{x:,}"


def change(new: int, old: int) -> str:
    return f"{100 * (new - old) / old:+.1f}%"


def render_report(config: dict, stats: dict[str, dict], triads: dict[str, dict], classes: list[dict]) -> str:
    labels = config["corpus"]["labels"]
    old = old_sizes(config)
    out = ["# Network construction report", "",
           "Generated by `uv run python -m huckfinn_cna.networks`. One directed word-adjacency network per",
           "text: nodes are lowercased Stanza lemmas of word tokens (ё → е), and each word links to the next",
           "word of the same sentence. Non-word tokens are skipped; no edge crosses a sentence boundary;",
           "self-loops are dropped. *Edges* are distinct directed pairs; *mutual pairs* are unordered node",
           "pairs linked in both directions; *isolated nodes* have no edge (they occur only in one-word",
           "sentences or only next to themselves).", "",
           "## Network size", "",
           "| Text | Translation | Sentences | Word tokens | Nodes | Isolated nodes | Edges | Total edge count | "
           "Mutual pairs | Self-loops dropped (occurrences) | Self-loop lemmas | Non-word tokens skipped |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t, s in stats.items():
        out.append(f"| {t} | {labels[t]} | {num(s['sentences'])} | {num(s['word_tokens'])} | {num(s['nodes'])} | "
                   f"{num(s['isolated_nodes'])} | {num(s['edges'])} | {num(s['edge_weight_total'])} | "
                   f"{num(s['mutual_pairs'])} | {num(s['self_loops_dropped'])} | {num(s['self_loop_lemmas'])} | "
                   f"{num(s['skipped_non_word_tokens'])} |")
    out += ["", "## Old and new network sizes", "",
            "Old: the archived mfinder input networks (data audit, `docs/audit/data_audit.json`): pymorphy2",
            "lemmas of the whole text as one token stream, so edges also crossed sentence and paragraph",
            "boundaries; self-loops removed. Old node counts are the nodes that occur in an edge, so the",
            "comparable new figure is nodes minus isolated nodes.", "",
            "The old-to-new change combines three differences: the new cleaning, Stanza instead of pymorphy2",
            "lemmas, and sentence-bounded edges. *New lemmas, crossing* isolates the last: it links the same",
            "new lemmas across sentence boundaries, as the old pipeline did (diagnostic only; not used).", "",
            "| Text | Translation | Old nodes | New nodes (with edges) | Change | Old edges | "
            "New lemmas, crossing | New edges | Change vs old | Change vs crossing |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for t, s in stats.items():
        o, linked = old[t], s["nodes"] - s["isolated_nodes"]
        out.append(f"| {t} | {labels[t]} | {num(o['nodes'])} | {num(linked)} | {change(linked, o['nodes'])} | "
                   f"{num(o['edges'])} | {num(s['edges_if_crossing'])} | {num(s['edges'])} | "
                   f"{change(s['edges'], o['edges'])} | {change(s['edges'], s['edges_if_crossing'])} |")
    out += ["", "## Connected 3-node triads", "",
            "Exact counts; igraph `motifs_randesu` and networkx `triadic_census` agree on every value",
            "(the run fails otherwise). IDs are mfinder subgraph IDs.", "",
            "| mfinder ID | Triad code | igraph class | " + " | ".join(stats) + " |",
            "|---|---|---|" + "---|" * len(stats)]
    for c in classes:
        out.append(f"| {c['mfinder_id']} | {c['triad_code']} | {c['igraph_class']} | "
                   + " | ".join(num(triads[t][c["mfinder_id"]]) for t in stats) + " |")
    return "\n".join(out) + "\n"


# --- Driver -----------------------------------------------------------------------


def config_classes(config: dict) -> list[dict]:
    """The triad table stored in config; must equal the decoded table."""
    if config["networks"]["motif_size"] != TRIAD_SIZE:
        raise NetworkError(f"motif_size must be {TRIAD_SIZE}: the networkx cross-check counts triads only")
    stored = config["networks"].get("triads", [])
    decoded = decode_triad_classes(config["networks"]["motif_size"])
    if stored != decoded:
        raise NetworkError("[[networks.triads]] in config differs from the decoded table; regenerate it with "
                           "`uv run python -m huckfinn_cna.networks --triad-table`")
    return stored


def run(config_path: Path = DEFAULT_CONFIG) -> dict:
    config = load_config(config_path)
    classes = config_classes(config)
    out_dir = repo_path(config, "networks_dir")
    out_dir.mkdir(parents=True, exist_ok=True)
    stats, triads = {}, {}
    for text_id in config["corpus"]["texts"]:
        rows = read_tagged(repo_path(config, "tagged_dir") / f"{text_id}.tsv")
        result = build_text(rows, config, classes)
        write_text(out_dir, text_id, result, config, classes)
        stats[text_id], triads[text_id] = result["stats"], result["triads"]
    report = repo_path(config, "network_report")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render_report(config, stats, triads, classes), encoding="utf-8")
    return {"stats": stats, "triads": triads}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--triad-table", action="store_true",
                        help="print the decoded [[networks.triads]] block for config/pipeline.toml and exit")
    parser.add_argument("--check-mfinder", nargs=2, type=Path, metavar=("INPUT", "OUT"),
                        help="check that mfinder's NREAL in OUT (_OUT.txt) equals the exact counts for INPUT")
    args = parser.parse_args()
    if args.triad_table:
        print(triad_table_toml(decode_triad_classes(load_config(args.config)["networks"]["motif_size"])), end="")
        return
    if args.check_mfinder:
        pairs = compare_nreal(*args.check_mfinder, config_classes(load_config(args.config)))
        print("mfinder NREAL equals igraph/networkx for all 13 triads:",
              ", ".join(f"{k}={v[0]}" for k, v in pairs.items()))
        return
    data = run(args.config)
    for text_id, s in data["stats"].items():
        print(f"{text_id}: {s['nodes']} nodes ({s['isolated_nodes']} isolated), {s['edges']} edges, "
              f"{s['mutual_pairs']} mutual pairs, {s['self_loops_dropped']} self-loops dropped")


if __name__ == "__main__":
    main()
